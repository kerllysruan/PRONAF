async function seedInversoes() {
  console.log(`Iniciando carga de ${inversoesData.length} inversões de referência...`);

  // Limpar dados anteriores se existirem para evitar duplicatas
  const { error: delError } = await supabase.from("inversoes_referencia").delete().neq("id", "00000000-0000-0000-0000-000000000000");
  if (delError) {
    console.warn("Aviso ao limpar tabela anterior:", delError.message);
  }

  // Inserir dados em lotes
  const batchSize = 30;
  for (let i = 0; i < inversoesData.length; i += batchSize) {
    const batch = inversoesData.slice(i, i + batchSize).map((item, idx) => ({
      ...item,
      ordem: i + idx + 1,
    }));

    const { error: insError } = await supabase.from("inversoes_referencia").insert(batch);
    if (insError) {
      console.error(`Erro ao inserir lote ${i} - ${i + batchSize}:`, insError);
      throw insError;
    }
    console.log(`Lote ${i + 1} a ${Math.min(i + batchSize, inversoesData.length)} inserido com sucesso!`);
  }

  const { count } = await supabase.from("inversoes_referencia").select("*", { count: "exact", head: true });
  console.log(`\n✅ Carga concluída com sucesso! Total na tabela: ${count} registros.`);
}

